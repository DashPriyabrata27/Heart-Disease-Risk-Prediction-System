import sys

import pandas as pd

from src.logger import logger
from src.exception import ProjectException

from src.components.model_prediction import ModelPrediction

from src.models.prediction_input import PredictionInput


# ==========================================================
# Prediction Pipeline
# ==========================================================

class PredictionPipeline:
    """
    Executes the complete heart disease
    prediction workflow.
    """

    # ======================================================
    # Constructor
    # ======================================================

    def __init__(self) -> None:
        """
        Initialize the Prediction Pipeline.

        The ModelPrediction component is
        initialized once and reused for
        prediction requests.
        """

        logger.info(
            "Initializing Prediction Pipeline."
        )

        self.predictor = ModelPrediction()

        logger.info(
            "Prediction Pipeline initialized successfully."
        )

    # ======================================================
    # Execute Prediction
    # ======================================================

    def predict(
        self,
        patient: PredictionInput
    ) -> dict:
        """
        Execute the prediction workflow.

        Parameters
        ----------
        patient : PredictionInput
            Validated and prepared patient input.

        Returns
        -------
        dict
            Prediction result generated by
            the Model Prediction component.
        """

        try:

            logger.info(
                "=" * 70
            )

            logger.info(
                "PREDICTION PIPELINE STARTED"
            )

            logger.info(
                "=" * 70
            )

            # ==================================================
            # Convert PredictionInput to DataFrame
            # ==================================================

            logger.info(
                "Converting PredictionInput to DataFrame."
            )

            input_data = pd.DataFrame(
                [patient.__dict__]
            )

            logger.info(
                "PredictionInput converted to DataFrame successfully."
            )

            # ==================================================
            # Execute Model Prediction
            # ==================================================

            logger.info(
                "Executing model prediction."
            )

            prediction_result = self.predictor.predict(
                input_data
            )

            logger.info(
                "Model prediction completed successfully."
            )

            # ==================================================
            # Pipeline Completed
            # ==================================================

            logger.info(
                "=" * 70
            )

            logger.info(
                "PREDICTION PIPELINE COMPLETED"
            )

            logger.info(
                "=" * 70
            )

            return prediction_result

        except Exception as error:

            logger.exception(
                "Prediction pipeline failed."
            )

            raise ProjectException(
                error,
                sys
            ) from error