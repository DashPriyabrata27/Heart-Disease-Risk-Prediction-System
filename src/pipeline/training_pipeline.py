"""
==========================================================
training_pipeline.py

Project
-------
Heart Disease Prediction

Description
-----------
Orchestrates the complete end-to-end machine learning
training workflow by executing all training components
in the correct sequence.

Responsibilities
----------------
✓ Execute data ingestion
✓ Execute data validation
✓ Load processed training and testing datasets
✓ Pass data to subsequent pipeline stages
==========================================================
"""

import sys

import pandas as pd

from src.logger import logger

from src.exception import ProjectException

from src.constants import (
    TRAIN_DATA_PATH,
    TEST_DATA_PATH
)

from src.components.data_ingestion import DataIngestion

from src.components.data_validation import DataValidation

from src.components.data_preprocessing import DataPreprocessing

from src.components.feature_selection import FeatureSelection

from src.components.model_trainer import ModelTrainer

from src.components.hyperparameter_tuning import HyperparameterTuning

from src.components.model_evaluation import ModelEvaluation

# ==========================================================
# Training Pipeline
# ==========================================================

class TrainingPipeline:
    """
    Orchestrates the complete end-to-end
    machine learning training workflow.
    """

    # ======================================================
    # Constructor
    # ======================================================

    def __init__(self) -> None:
        """
        Initialize the Training Pipeline.
        """

        logger.info(
            "Initializing Training Pipeline."
        )

        logger.info(
            "Training Pipeline initialized successfully."
        )

    # ======================================================
    # Execute Data Ingestion
    # ======================================================

    def execute_data_ingestion(
        self
    ) -> None:
        """
        Execute the data ingestion component.

        Returns
        -------
        None
        """

        try:

            logger.info(
                "Starting data ingestion stage."
            )

            data_ingestion = DataIngestion()

            data_ingestion.initiate_data_ingestion()

            logger.info(
                "Data ingestion stage completed successfully."
            )

        except Exception as error:

            logger.exception(
                "Data ingestion stage failed."
            )

            raise ProjectException(
                error,
                sys
            ) from error

    # ======================================================
    # Execute Data Validation
    # ======================================================

    def execute_data_validation(
        self
    ) -> None:
        """
        Execute the data validation component.

        Returns
        -------
        None
        """

        try:

            logger.info(
                "Starting data validation stage."
            )

            data_validation = DataValidation()

            data_validation.initiate_data_validation()

            logger.info(
                "Data validation stage completed successfully."
            )

        except Exception as error:

            logger.exception(
                "Data validation stage failed."
            )

            raise ProjectException(
                error,
                sys
            ) from error

    # ======================================================
    # Load Training and Testing Data
    # ======================================================

    def load_training_data(
        self
    ) -> tuple[pd.DataFrame, pd.DataFrame]:
        """
        Load the training and testing datasets
        generated by the data ingestion stage.

        Returns
        -------
        tuple[pd.DataFrame, pd.DataFrame]
            Training and testing DataFrames.
        """

        try:

            logger.info(
                "Loading training and testing datasets."
            )

            train_df = pd.read_csv(
                TRAIN_DATA_PATH
            )

            test_df = pd.read_csv(
                TEST_DATA_PATH
            )

            logger.info(
                f"Training dataset loaded successfully. "
                f"Shape: {train_df.shape}"
            )

            logger.info(
                f"Testing dataset loaded successfully. "
                f"Shape: {test_df.shape}"
            )

            return train_df, test_df

        except Exception as error:

            logger.exception(
                "Failed to load training and testing datasets."
            )

            raise ProjectException(
                error,
                sys
            ) from error
    
        # ======================================================
    # Execute Data Preprocessing
    # ======================================================

    def execute_data_preprocessing(
        self,
        train_df: pd.DataFrame,
        test_df: pd.DataFrame
    ) -> tuple[pd.DataFrame, pd.DataFrame]:
        """
        Execute the data preprocessing stage.

        Parameters
        ----------
        train_df : pd.DataFrame
            Training dataset.

        test_df : pd.DataFrame
            Testing dataset.

        Returns
        -------
        tuple[pd.DataFrame, pd.DataFrame]
            Preprocessed training and testing datasets.
        """

        try:

            logger.info(
                "Starting data preprocessing stage."
            )

            data_preprocessing = DataPreprocessing()

            preprocessing_output = (
                data_preprocessing.initiate_data_preprocessing(
                    train_df=train_df,
                    test_df=test_df
                )
            )

            processed_train_df = (
                preprocessing_output["train_df"]
            )

            processed_test_df = (
                preprocessing_output["test_df"]
            )

            logger.info(
                f"Preprocessed training dataset shape: "
                f"{processed_train_df.shape}"
            )

            logger.info(
                f"Preprocessed testing dataset shape: "
                f"{processed_test_df.shape}"
            )

            logger.info(
                "Data preprocessing stage completed successfully."
            )

            return (
                processed_train_df,
                processed_test_df
            )

        except Exception as error:

            logger.exception(
                "Data preprocessing stage failed."
            )

            raise ProjectException(
                error,
                sys
            ) from error

    # ======================================================
    # Execute Feature Selection
    # ======================================================

    def execute_feature_selection(
        self,
        train_df: pd.DataFrame,
        test_df: pd.DataFrame
    ) -> dict:
        """
        Execute the feature selection stage.

        Parameters
        ----------
        train_df : pd.DataFrame
            Preprocessed training dataset.

        test_df : pd.DataFrame
            Preprocessed testing dataset.

        Returns
        -------
        dict
            Selected training and testing
            features and target values.
        """

        try:

            logger.info(
                "Starting feature selection stage."
            )

            feature_selection = FeatureSelection()

            feature_output = (
                feature_selection.initiate_feature_selection(
                    train_df=train_df,
                    test_df=test_df
                )
            )

            logger.info(
                f"Training feature shape: "
                f"{feature_output['X_train'].shape}"
            )

            logger.info(
                f"Testing feature shape: "
                f"{feature_output['X_test'].shape}"
            )

            logger.info(
                "Feature selection stage completed successfully."
            )

            return feature_output

        except Exception as error:

            logger.exception(
                "Feature selection stage failed."
            )

            raise ProjectException(
                error,
                sys
            ) from error

    # ======================================================
    # Execute Model Training
    # ======================================================

    def execute_model_training(
        self,
        feature_output: dict
    ) -> dict:
        """
        Execute the model training stage.

        Parameters
        ----------
        feature_output : dict
            Output generated by the feature
            selection component.

        Returns
        -------
        dict
            Model training results.
        """

        try:

            logger.info(
                "Starting model training stage."
            )

            model_trainer = ModelTrainer()

            trainer_output = (
                model_trainer.initiate_model_trainer(
                    X_train=feature_output["X_train"],
                    X_test=feature_output["X_test"],
                    y_train=feature_output["y_train"],
                    y_test=feature_output["y_test"]
                )
            )

            logger.info(
                "Model training stage completed successfully."
            )

            return trainer_output

        except Exception as error:

            logger.exception(
                "Model training stage failed."
            )

            raise ProjectException(
                error,
                sys
            ) from error

    # ======================================================
    # Execute Hyperparameter Tuning
    # ======================================================

    def execute_hyperparameter_tuning(
        self,
        X_train,
        y_train
    ) -> dict:
        """
        Execute the hyperparameter tuning stage.

        Parameters
        ----------
        X_train
            Training feature matrix.

        y_train
            Training target values.

        Returns
        -------
        dict
            Hyperparameter tuning results.
        """

        try:

            logger.info(
                "Starting hyperparameter tuning stage."
            )

            hyperparameter_tuning = HyperparameterTuning()

            tuning_output = (
                hyperparameter_tuning.initiate_hyperparameter_tuning(
                    X_train=X_train,
                    y_train=y_train
                )
            )

            logger.info(
                "Hyperparameter tuning stage "
                "completed successfully."
            )

            logger.info(
                f"Best hyperparameters: "
                f"{tuning_output['best_parameters']}"
            )

            logger.info(
                f"Best cross-validation score: "
                f"{tuning_output['best_score']:.4f}"
            )

            return tuning_output

        except Exception as error:

            logger.exception(
                "Hyperparameter tuning stage failed."
            )

            raise ProjectException(
                error,
                sys
            ) from error

    # ======================================================
    # Execute Model Evaluation
    # ======================================================

    def execute_model_evaluation(
        self,
        X_test,
        y_test
    ) -> dict:
        """
        Execute the model evaluation stage.

        Parameters
        ----------
        X_test
            Testing feature matrix.

        y_test
            Testing target values.

        Returns
        -------
        dict
            Model evaluation results.
        """

        try:

            logger.info(
                "Starting model evaluation stage."
            )

            model_evaluation = ModelEvaluation()

            evaluation_output = (
                model_evaluation.initiate_model_evaluation(
                    X_test=X_test,
                    y_test=y_test
                )
            )

            logger.info(
                "Model evaluation stage "
                "completed successfully."
            )

            logger.info(
                f"Final model accuracy: "
                f"{evaluation_output['metrics']['accuracy']:.4f}"
            )

            logger.info(
                f"Final model F1 score: "
                f"{evaluation_output['metrics']['f1_score']:.4f}"
            )

            logger.info(
                f"Final model ROC-AUC: "
                f"{evaluation_output['metrics']['roc_auc']:.4f}"
            )

            return evaluation_output

        except Exception as error:

            logger.exception(
                "Model evaluation stage failed."
            )

            raise ProjectException(
                error,
                sys
            ) from error

    # ======================================================
    # Start Complete Training Pipeline
    # ======================================================

    def start_training(self) -> dict:
        """
        Execute the complete end-to-end
        machine learning training pipeline.

        Returns
        -------
        dict
            Complete training pipeline result.
        """

        try:

            logger.info(
                "=" * 70
            )

            logger.info(
                "TRAINING PIPELINE STARTED"
            )

            logger.info(
                "=" * 70
            )

            # ==================================================
            # Data Ingestion
            # ==================================================

            self.execute_data_ingestion()

            # ==================================================
            # Data Validation
            # ==================================================

            self.execute_data_validation()

            # ==================================================
            # Load Training and Testing Data
            # ==================================================

            train_df, test_df = (
                self.load_training_data()
            )

            # ==================================================
            # Data Preprocessing
            # ==================================================

            (
                processed_train_df,
                processed_test_df
            ) = self.execute_data_preprocessing(
                train_df=train_df,
                test_df=test_df
            )

            # ==================================================
            # Feature Selection
            # ==================================================

            feature_output = (
                self.execute_feature_selection(
                    train_df=processed_train_df,
                    test_df=processed_test_df
                )
            )

            # ==================================================
            # Model Training
            # ==================================================

            trainer_output = (
                self.execute_model_training(
                    feature_output=feature_output
                )
            )

            # ==================================================
            # Hyperparameter Tuning
            # ==================================================

            tuning_output = (
                self.execute_hyperparameter_tuning(
                    X_train=trainer_output["X_train"],
                    y_train=trainer_output["y_train"]
                )
            )

            # ==================================================
            # Model Evaluation
            # ==================================================

            evaluation_output = (
                self.execute_model_evaluation(
                    X_test=trainer_output["X_test"],
                    y_test=trainer_output["y_test"]
                )
            )

            # ==================================================
            # Training Pipeline Completed
            # ==================================================

            logger.info(
                "=" * 70
            )

            logger.info(
                "TRAINING PIPELINE COMPLETED SUCCESSFULLY"
            )

            logger.info(
                "=" * 70
            )

            return {

                "status": "Success",

                "message": (
                    "Training pipeline executed "
                    "successfully."
                ),

                "baseline_model": (
                    trainer_output.get(
                        "best_model_name"
                    )
                ),

                "best_parameters": (
                    tuning_output[
                        "best_parameters"
                    ]
                ),

                "best_cv_score": (
                    tuning_output[
                        "best_score"
                    ]
                ),

                "evaluation": evaluation_output

            }

        except Exception as error:

            logger.exception(
                "Training pipeline failed."
            )

            raise ProjectException(
                error,
                sys
            ) from error